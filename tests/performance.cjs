 assert.equal(e.requests.length,1,'repeat navigation uses cache');
 e.w.eval(fs.readFileSync('property-listings.js','utf8')); await tick();
 assert.equal(e.w.document.querySelectorAll('.property').length,1);
 assert.equal(e.requests.length,1,'catalogue renders without another remote call');
 const form=e.w.document.getElementById('listingFilters');
 form.elements.namedItem('city').value='Noida';form.dispatchEvent(new e.w.Event('submit',{cancelable:true}));await tick();
 assert.equal(e.w.document.querySelectorAll('.property').length,0);
