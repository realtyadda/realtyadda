const assert = require('node:assert/strict');
const fs = require('node:fs');
const {JSDOM} = require('jsdom');
const apiSource = fs.readFileSync('realtyadda-api.js','utf8');
function environment(page='buy.html') {
  const dom = new JSDOM(fs.readFileSync(page,'utf8'),{url:'https://www.realtyadda.in/'+page,runScripts:'outside-only'});
  const w=dom.window;
  let now=100000;
  w.Date.now=()=>now;
  const requests=[];
  const append=w.document.head.appendChild.bind(w.document.head);
  w.document.head.appendChild = el => { if(el.tagName==='SCRIPT' && el.src.includes('script.google.com')) { requests.push(el); return el; } return append(el); };
  w.eval(apiSource);
  return {dom,w,requests,advance:ms=>now+=ms,reply(data,index=requests.length-1){const u=new URL(requests[index].src);w[u.searchParams.get('callback')](data);}};
}
const tick=()=>new Promise(resolve=>setImmediate(resolve));
